"""Development-only: freeze the existing preset RGB data into native C++.

The generated source is checked in. Building/running the filter needs no Python.
"""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'distribution/Digital8_Anime'))
import digital8_converter as converter

lines = ['// Generated by photoshop/generate_palettes.py; RGB data only.',
         '#include "renderer.h"', 'namespace digital8 {',
         'const std::vector<Palette>& palettes() {',
         'static const std::vector<Palette> data = {']
for machine_id, machine in enumerate(('pc8801', 'pc9801', 'anime')):
    for palette in converter.palettes_for(machine):
        colours = ','.join('{' + ','.join(map(str, c)) + '}' for c in palette.colours)
        lines.append('{' + f'{machine_id},{json.dumps(palette.id)},{json.dumps(palette.label,ensure_ascii=False)},' + '{' + colours + '}},')
lines.extend(['}; return data;', '}'])
pairs = sorted(converter.pc88_two_colour.OBSERVED_PAIRS)
lines.extend(['bool observed_pc88(int a,int b) { if(a>b){int t=a;a=b;b=t;} return ' +
              ' || '.join(f'(a=={a}&&b=={b})' for a,b in pairs) + '; }', '}'])
path = ROOT / 'photoshop/native/palettes.cpp'
path.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(path)
